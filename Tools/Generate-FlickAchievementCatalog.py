"""Keep the C++ Steam catalogue and Steamworks setup handoff in sync."""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'Deliverables/Steam-Achievements-2026-11-03'
OUT = ROOT / 'Deliverables/Steamworks-Setup-5548920'
OUT.mkdir(exist_ok=True)
items = json.loads((ASSETS / 'source-manifest.json').read_text())['achievements']
assert len(items) == 48 and len({a['id'] for a in items}) == 48
def symbol(a):
    return ''.join(x.title() for x in a['slug'].split('_'))
def stat(a):
    # These multi-step conditions unlock directly; their progress stats were
    # deliberately omitted from the published Steamworks schema.
    direct_metrics = {'unique_bob_pockets_in_one_match', 'competitive_placements_in_one_playlist'}
    return 'STAT_' + a['proposed_metric'].upper() if a['range']['max'] > 1 and a['proposed_metric'] not in direct_metrics else ''
best_metrics = {'competitive_placements_in_one_playlist', 'unique_mastered_practice_packs',
    'unique_puck_archetypes_played', 'unique_competitive_playlists_won',
    'mastered_foundation_focuses', 'mastered_skilled_focuses', 'mastered_expert_focuses',
    'fully_placed_competitive_playlists', 'unique_bob_pockets_in_one_match'}
lines = ['// Generated by Tools/Generate-FlickAchievementCatalog.py. API names match the asset handoff.',
    '#pragma once', '#include "CoreMinimal.h"', '', 'namespace FlickAchievements', '{',
    '    constexpr uint32 AppId = 5548920;', '    enum class EId : uint8', '    {']
lines += ['        ' + symbol(a) + ',' for a in items]
lines += ['        Count', '    };', '    constexpr int32 Count = static_cast<int32>(EId::Count);',
    '    struct FDefinition { const TCHAR* Api; const TCHAR* Name; const TCHAR* Stat; int32 Goal; bool bBest; };',
    '    inline constexpr FDefinition Definitions[] = {']
for a in items:
    name = a['name'].replace('"', '\\"')
    lines.append(f'        {{TEXT("{a["id"]}"), TEXT("{name}"), TEXT("{stat(a)}"), {a["range"]["max"]}, {str(a["proposed_metric"] in best_metrics).lower()}}},')
lines += ['    };', '    static_assert(UE_ARRAY_COUNT(Definitions) == Count);',
    '    inline const FDefinition& Get(EId Id) { return Definitions[static_cast<int32>(Id)]; }',
    '    inline int32 Index(EId Id) { return static_cast<int32>(Id); }', '}']
(ROOT / 'Source/FLICK/Core/FlickAchievementCatalog.h').write_text('\n'.join(lines) + '\n')
stats = {}
for a in items:
    key = stat(a)
    if not key:
        continue
    row = stats.setdefault(key, {'api_name': key, 'type': 'INT', 'default': 0, 'min': 0,
        'max': 0, 'increment_only': 'Yes', 'set_by': 'Client', 'purpose': 'Achievement progress'})
    row['max'] = max(row['max'], a['range']['max'])
internal = [
    ('STAT_INTERNAL_ARCHETYPE_MASK', 511, 'Cross-device unique archetype tracking; attach to no achievement'),
    ('STAT_INTERNAL_PRACTICE_MASK', 4095, 'Cross-device unique mastered packs; attach to no achievement'),
    ('STAT_INTERNAL_RANKED_WIN_MASK', 15, 'Cross-device competitive playlist wins; attach to no achievement'),
    ('STAT_INTERNAL_PLACED_MASK', 15, 'Cross-device completed placements; attach to no achievement')]
for key, maximum, purpose in internal:
    stats[key] = {'api_name': key, 'type': 'INT', 'default': 0, 'min': 0, 'max': maximum,
        'increment_only': 'Yes', 'set_by': 'Client', 'purpose': purpose}
with (OUT / 'stats-to-create.csv').open('w', newline='', encoding='utf-8-sig') as f:
    writer = csv.DictWriter(f, fieldnames=list(next(iter(stats.values())).keys()))
    writer.writeheader(); writer.writerows(stats.values())
with (OUT / 'achievement-stat-links.csv').open('w', newline='', encoding='utf-8-sig') as f:
    writer = csv.writer(f)
    writer.writerow(['achievement_api_name', 'display_name', 'progress_stat', 'progress_min', 'progress_max', 'unlock'])
    for a in items:
        writer.writerow([a['id'], a['name'], stat(a), 0 if stat(a) else '', a['range']['max'] if stat(a) else '', a['unlock_condition']])
doc = ['# Steamworks setup for FLICK - App ID 5548920', '',
    'Create these stats in Steamworks > FLICK > Stats & Achievements > Stats, then publish the configuration.',
    'Use the API names exactly. All are INT, default 0, minimum 0, Set By Client. '
    'Increment Only is recommended but is not required by the integration; the game already preserves monotonic progress. '
    'If Max Change is enabled, allow at least the listed maximum so queued offline progress can upload. '
    'Achievement progress ranges below are independent of the shared stat maximum.', '',
    'A 0-1 achievement has no progress stat and no progress counter. The game unlocks it directly. '
    'Corner Office and Rank and File also unlock directly without a Steam progress bar; their conditions remain four unique holes in one match and five placements in one playlist.', '',
    '| Stat API name | Stat range | Attach to achievement (achievement progress range) |', '|---|---|---|']
for key, row in stats.items():
    matches = [f'{a["name"]} (`{a["id"]}`, 0-{a["range"]["max"]})' for a in items if stat(a) == key]
    doc.append(f'| `{key}` | 0-{row["max"]} | ' + '<br>'.join(matches or [row['purpose']]) + ' |')
doc += ['', '## Direct unlocks - leave Progress Stat empty', '', '| Achievement | API name |', '|---|---|']
doc += [f'| {a["name"]} | `{a["id"]}` |' for a in items if not stat(a)]
doc += ['', '## Important details', '',
    '- Shared career win stat: Arena Veteran uses progress 0-15; Century Club uses 0-100 on the same stat.',
    '- Corner Office uses the best number of unique holes reached in one match, not a sum across matches.',
    '- Rank and File uses the highest placement count in one playlist, never a sum across playlists.',
    '- The four INTERNAL stats store bitmasks to merge unique unlock requirements across computers. They do not create extra achievement progress bars.',
    '- The exact achievement API names must match `achievement-stat-links.csv`; display names alone are insufficient.',
    '- INT plus the listed ranges is sufficient with Steam defaults (Client and zero). Leave Max Change disabled, and leave the four INTERNAL stats unlinked from achievements.',
    '- Publishing the stats and owning/accessing App 5548920 in Steam are required for live Steam verification.',
    '- [Valve: Stats and Achievements](https://partner.steamgames.com/doc/features/achievements)',
    '- [Valve: ISteamUserStats](https://partner.steamgames.com/doc/api/ISteamUserStats)', '']
(OUT / 'README.md').write_text('\n'.join(doc), encoding='utf-8')
print(f'Generated 48 achievement definitions, {len(stats)} Steam stats, and full mapping in {OUT}')
